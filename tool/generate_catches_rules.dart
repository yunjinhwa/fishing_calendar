import 'dart:io';

import 'package:fishing_build/data/remote/firestore_catches_codec.dart';

// Keep the Rules grammar identical to the Dart reader. Run with --check in
// verification; without arguments it replaces only the generated block.
void main(List<String> arguments) {
  final file = File.fromUri(Platform.script.resolve('../firestore.rules'));
  final source = file.readAsStringSync().replaceAll('\r\n', '\n');
  const start = '    // BEGIN GENERATED CATCHES GRAMMAR';
  const end = '    // END GENERATED CATCHES GRAMMAR';
  final from = source.indexOf(start);
  final to = source.indexOf(end, from);
  if (from < 0 || to < 0) throw StateError('Missing catches grammar markers.');
  String quoted(String value) =>
      "'${value.replaceAll(r'\', r'\\').replaceAll("'", r"\'")}'";
  final block =
      '''$start
    // Generated by dart run tool/generate_catches_rules.dart. Do not edit.
    // Separate bounds avoid RE2's nested repetition expansion limit.
    function validCatchesJson(value) {
      return value is string
        && value.size() <= ${FirestoreCatchesCodec.maxEncodedLength}
        && value.matches(${quoted(FirestoreCatchesCodec.wholeArrayPattern)})
        && !value.matches(${quoted(FirestoreCatchesCodec.whitespaceCatchPattern)})
        && !value.matches(${quoted(FirestoreCatchesCodec.oversizedNamePattern)})
        && value.split('"speciesName":').size() <= 101;
    }
$end''';
  final updated = source.replaceRange(from, to + end.length, block);
  if (arguments.contains('--check')) {
    if (updated != source) {
      stderr.writeln(
        'Catches grammar is stale; run dart run tool/generate_catches_rules.dart.',
      );
      exitCode = 1;
    } else {
      stdout.writeln('Catches Rules grammar matches the Dart codec.');
    }
    return;
  }
  file.writeAsStringSync(updated);
  stdout.writeln('Updated the generated catches grammar.');
}
